import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import { test } from 'node:test'
import { Pool } from 'pg'
import { syncAiEnergyOrders } from './ai-energy-order-worker.server'

const connectionString = process.env.PLATFORM_TEST_DATABASE_URL

test('AI trusteeship worker persists supplier outcomes and claims each real PostgreSQL row once', { skip: !connectionString }, async () => {
  const databaseUrl = new URL(connectionString!)
  const databaseName = databaseUrl.pathname.replace(/^\//, '')
  assert.ok(['127.0.0.1', 'localhost', 'postgres'].includes(databaseUrl.hostname), 'integration DB must be loopback-only or the dedicated isolated postgres service')
  assert.ok(databaseName.startsWith('tg_ai_energy_order_test_'), 'integration DB name must use the disposable test prefix')

  const schema = 'ai_energy_order_' + randomUUID().replaceAll('-', '')
  const admin = new Pool({ connectionString, max: 2 })
  const pool = new Pool({ connectionString, options: '-c search_path=' + schema, max: 5 })
  const savedEnv = {
    app: process.env.APP_ENV,
    signerUrl: process.env.TRON_SIGNER_URL,
    signerToken: process.env.TRON_SIGNER_TOKEN,
    energyActions: process.env.PLATFORM_ENERGY_ORDER_ACTIONS,
  }

  try {
    await admin.query('CREATE SCHEMA ' + schema)
    await pool.query(
      "CREATE TABLE t_energy_ai_trusteeship (" +
        "rid integer PRIMARY KEY, bot_rid integer NOT NULL, tg_uid bigint NOT NULL, wallet_addr varchar(100) NOT NULL, " +
        "status smallint NOT NULL DEFAULT 0, per_buy_energy_quantity integer NOT NULL, " +
        "total_buy_energy_quantity bigint NOT NULL DEFAULT 0, total_used_trx numeric(14,2) NOT NULL DEFAULT 0, " +
        "total_buy_quantity integer NOT NULL DEFAULT 0, is_buy char(1) NOT NULL DEFAULT 'N', " +
        "is_notice char(1) NOT NULL DEFAULT 'N', is_notice_admin char(1) NOT NULL DEFAULT 'N', " +
        "last_buy_time timestamp, last_used_trx numeric(14,2), comments varchar(2000), " +
        "create_time timestamp NOT NULL DEFAULT now(), update_time timestamp)"
    )
    await pool.query(
      "CREATE TABLE t_energy_platform_bot (" +
        "rid integer PRIMARY KEY, bot_rid integer NOT NULL, poll_group char(1) NOT NULL, status smallint NOT NULL DEFAULT 0, " +
        "is_open_ai_trusteeship char(1) NOT NULL DEFAULT 'Y', per_energy_day integer NOT NULL, " +
        "trx_price_energy_32000 integer NOT NULL, trx_price_energy_65000 integer NOT NULL, " +
        "agent_tg_uid bigint, agent_per_price numeric(18,6), ai_trusteeship_recovery_type varchar(20) NOT NULL DEFAULT '1')"
    )
    await pool.query(
      "CREATE TABLE t_energy_platform (" +
        "rid integer PRIMARY KEY, poll_group char(1) NOT NULL, platform_name smallint NOT NULL, status smallint NOT NULL DEFAULT 0, " +
        "platform_uid varchar(100) NOT NULL, permission_id integer NOT NULL DEFAULT 0, platform_balance numeric(28,6) NOT NULL DEFAULT 0, " +
        "platform_apikey varchar(3000), seq_sn integer NOT NULL DEFAULT 0)"
    )
    await pool.query(
      "CREATE TABLE t_telegram_bot_user (" +
        "rid integer PRIMARY KEY, bot_rid integer NOT NULL, tg_uid bigint NOT NULL, cash_trx numeric(20,6) NOT NULL DEFAULT 0, " +
        "UNIQUE(bot_rid,tg_uid))"
    )
    await pool.query(
      "CREATE TABLE t_energy_platform_order (" +
        "rid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, energy_platform_rid integer NOT NULL, " +
        "energy_platform_bot_rid integer NOT NULL, platform_name smallint NOT NULL, platform_uid varchar(50) NOT NULL, " +
        "receive_address varchar(50) NOT NULL, platform_order_id varchar(100) NOT NULL, energy_amount integer NOT NULL, " +
        "energy_day smallint NOT NULL, energy_time timestamp NOT NULL, source_type smallint NOT NULL DEFAULT 1, " +
        "recovery_status smallint NOT NULL DEFAULT 1, use_trx numeric(14,6), recovery_time timestamp)"
    )

    await pool.query(
      "INSERT INTO t_energy_ai_trusteeship(rid,bot_rid,tg_uid,wallet_addr,status,per_buy_energy_quantity,is_buy,create_time) VALUES" +
        "(61001,611,501,'Tsuccess',0,65000,'Y',now())," +
        "(61002,612,601,'Tambiguous',0,65000,'Y',now())," +
        "(61003,613,701,'Tconcurrent',0,65000,'Y',now())"
    )
    await pool.query(
      "INSERT INTO t_energy_platform_bot(rid,bot_rid,poll_group,status,is_open_ai_trusteeship,per_energy_day,trx_price_energy_32000,trx_price_energy_65000,agent_tg_uid,agent_per_price) VALUES" +
        "(61101,611,'A',0,'Y',1,6,12,502,0.2)," +
        "(61201,612,'B',0,'Y',1,6,12,NULL,NULL)," +
        "(61301,613,'C',0,'Y',1,6,12,NULL,NULL)"
    )
    await pool.query(
      "INSERT INTO t_energy_platform(rid,poll_group,platform_name,status,platform_uid,permission_id,platform_balance,platform_apikey,seq_sn) VALUES" +
        "(62101,'A',3,0,'signer-account',9,90000,'encrypted-fixture-a',1)," +
        "(62102,'B',3,0,'signer-account',9,90000,'encrypted-fixture-b',1)," +
        "(62103,'C',3,0,'signer-account',9,90000,'encrypted-fixture-c',1)"
    )
    await pool.query(
      "INSERT INTO t_telegram_bot_user(rid,bot_rid,tg_uid,cash_trx) VALUES" +
        "(63101,611,501,100),(63102,611,502,10),(63103,612,601,100),(63104,613,701,100)"
    )

    Object.assign(process.env, {
      APP_ENV: 'development',
      TRON_SIGNER_URL: 'http://signer.test',
      TRON_SIGNER_TOKEN: 'test-signer-token-012345678901234567890123456789',
      PLATFORM_ENERGY_ORDER_ACTIONS: 'true',
    })

    const signerRequests: Array<{ url: string; body: Record<string, unknown> }> = []
    const successfulSigner = (async (input: RequestInfo | URL, init?: RequestInit) => {
      const url = String(input)
      const body = JSON.parse(String(init?.body ?? '{}')) as Record<string, unknown>
      signerRequests.push({ url, body })
      return Response.json({ code: 200, data: { txid: 'fixture-stake-order', use_trx: '2.125000' } })
    }) as typeof fetch

    const success = await syncAiEnergyOrders({ pool, batchSize: 1, fetcher: successfulSigner, logger: { error() {} } })
    assert.deepEqual(success, { skipped: false, scanned: 1, succeeded: 1, failed: 0, manual: 0 })
    assert.equal(signerRequests.length, 1)
    assert.equal(signerRequests[0].url, 'http://signer.test/api/internal/tron/sign')
    assert.equal(signerRequests[0].body.operation, 'delegate_resource')
    assert.equal(signerRequests[0].body.private_key_ciphertext, 'encrypted-fixture-a')
    assert.equal('private_key' in signerRequests[0].body, false)

    const successfulOrder = await pool.query(
      'SELECT platform_order_id,source_type,recovery_status,use_trx::text FROM t_energy_platform_order WHERE energy_platform_bot_rid=61101'
    )
    assert.deepEqual(successfulOrder.rows[0], {
      platform_order_id: 'fixture-stake-order',
      source_type: 3,
      recovery_status: 2,
      use_trx: '2.125000',
    })
    const successfulAccount = await pool.query(
      "SELECT is_buy,is_notice,is_notice_admin,total_buy_quantity,total_buy_energy_quantity,total_used_trx::text FROM t_energy_ai_trusteeship WHERE rid=61001"
    )
    assert.deepEqual(successfulAccount.rows[0], {
      is_buy: 'N',
      is_notice: 'Y',
      is_notice_admin: 'N',
      total_buy_quantity: 1,
      total_buy_energy_quantity: '65000',
      total_used_trx: '6.00',
    })
    const balances = await pool.query('SELECT tg_uid::text,cash_trx::text FROM t_telegram_bot_user WHERE bot_rid=611 ORDER BY tg_uid')
    assert.deepEqual(balances.rows, [
      { tg_uid: '501', cash_trx: '94.000000' },
      { tg_uid: '502', cash_trx: '9.800000' },
    ])

    let ambiguousSignerCalls = 0
    const ambiguousSigner = (async () => {
      ambiguousSignerCalls++
      throw new Error('fixture timeout')
    }) as typeof fetch
    const ambiguous = await syncAiEnergyOrders({
      pool,
      batchSize: 1,
      fetcher: ambiguousSigner,
      logger: { error() {} },
    })
    assert.deepEqual(ambiguous, { skipped: false, scanned: 1, succeeded: 0, failed: 0, manual: 1 })
    const manualReview = await pool.query('SELECT is_buy,is_notice_admin,comments FROM t_energy_ai_trusteeship WHERE rid=61002')
    assert.equal(manualReview.rows[0].is_buy, 'N')
    assert.equal(manualReview.rows[0].is_notice_admin, 'Y')
    assert.match(manualReview.rows[0].comments, /人工核查/)
    assert.equal((await pool.query('SELECT count(*)::int AS count FROM t_energy_platform_order WHERE energy_platform_bot_rid=61201')).rows[0].count, 0)
    let enteredSigner!: () => void
    let releaseSigner!: () => void
    const signerEntered = new Promise<void>(resolve => { enteredSigner = resolve })
    const signerReleased = new Promise<void>(resolve => { releaseSigner = resolve })
    let concurrentSignerCalls = 0
    const slowSigner = (async () => {
      concurrentSignerCalls++
      enteredSigner()
      await signerReleased
      return Response.json({ code: 200, data: { txid: 'fixture-concurrent-order', use_trx: '1.000000' } })
    }) as typeof fetch
    const firstRun = syncAiEnergyOrders({ pool, batchSize: 1, fetcher: slowSigner, logger: { error() {} } })
    await signerEntered
    const secondRun = await syncAiEnergyOrders({ pool, batchSize: 1, fetcher: successfulSigner, logger: { error() {} } })
    releaseSigner()
    const firstRunResult = await firstRun

    assert.deepEqual(secondRun, { skipped: false, scanned: 0, succeeded: 0, failed: 0, manual: 0 })
    assert.deepEqual(firstRunResult, { skipped: false, scanned: 1, succeeded: 1, failed: 0, manual: 0 })
    assert.equal(concurrentSignerCalls, 1)
    assert.equal(
      (await pool.query('SELECT count(*)::int AS count FROM t_energy_platform_order WHERE energy_platform_bot_rid=61301')).rows[0].count,
      1,
    )
    assert.deepEqual(
      await syncAiEnergyOrders({ pool, batchSize: 1, fetcher: successfulSigner, logger: { error() {} } }),
      { skipped: false, scanned: 0, succeeded: 0, failed: 0, manual: 0 },
    )
    assert.equal(ambiguousSignerCalls, 1)
  } finally {
    for (const [key, value] of Object.entries({
      APP_ENV: savedEnv.app,
      TRON_SIGNER_URL: savedEnv.signerUrl,
      TRON_SIGNER_TOKEN: savedEnv.signerToken,
      PLATFORM_ENERGY_ORDER_ACTIONS: savedEnv.energyActions,
    })) {
      if (value == null) delete process.env[key]
      else process.env[key] = value
    }
    await pool.end()
    await admin.query('DROP SCHEMA IF EXISTS ' + schema + ' CASCADE').catch(() => undefined)
    await admin.end()
  }
})
