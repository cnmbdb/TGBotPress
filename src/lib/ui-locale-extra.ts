export function translateUiText(value: string, locale: Locale): string {
  if (locale === "zh-CN") return value
  const exact = messages[value]?.[locale]
  if (exact !== undefined) return exact
  const monitorPackages = /^(\d+) 个监控包$/.exec(value)
  if (monitorPackages) {
    return locale === "en"
      ? monitorPackages[1] + " monitoring packages"
      : locale === "ru"
        ? "Пакетов мониторинга: " + monitorPackages[1]
        : "監視パッケージ " + monitorPackages[1] + " 個"
  }
  const translated = translateText(value, locale)
  if (translated !== value) return translated
  const leadingLength = value.length - value.trimStart().length
  const trailingLength = value.length - value.trimEnd().length
  const core = value.trim()
  if (core && core !== value) {
    const trimmedTranslation = messages[core]?.[locale] ?? translateText(core, locale)
    if (trimmedTranslation !== core) return value.slice(0, leadingLength) + trimmedTranslation + value.slice(value.length - trailingLength)
  }
  return value
}
